// Backup completo do banco usando o SUPABASE_ACCESS_TOKEN do .env.local.
// Não precisa de Docker nem da senha do Postgres: a Management API roda SQL como `postgres`.
//
//   pnpm backup
//
// Gera backups/<data>/{schema.sql, data.sql, dados.json, MANIFEST.json}.
import { mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs'

const env = { ...process.env }
if (existsSync('.env.local')) {
  for (const line of readFileSync('.env.local', 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)$/)
    if (m && !env[m[1]]) env[m[1]] = m[2].trim().replace(/^["']|["']$/g, '')
  }
}

const token = env.SUPABASE_ACCESS_TOKEN
const ref = (env.SUPABASE_PROJECT_REF || env.NEXT_PUBLIC_SUPABASE_URL || '').match(/[a-z]{20}/)?.[0]
if (!token) fatal('Falta SUPABASE_ACCESS_TOKEN no .env.local (Dashboard > Account > Access Tokens).')
if (!ref) fatal('Não consegui deduzir o project ref de NEXT_PUBLIC_SUPABASE_URL.')

async function sql(query) {
  const r = await fetch(`https://api.supabase.com/v1/projects/${ref}/database/query`, {
    method: 'POST',
    headers: { Authorization: `Bearer ${token}`, 'content-type': 'application/json' },
    body: JSON.stringify({ query }),
  })
  const body = await r.json()
  if (!r.ok) fatal(`SQL falhou (${r.status}): ${body.message || JSON.stringify(body).slice(0, 200)}`)
  return body
}

const lit = (v) => {
  if (v === null || v === undefined) return 'null'
  if (typeof v === 'number') return String(v)
  if (typeof v === 'boolean') return v ? 'true' : 'false'
  const s = typeof v === 'object' ? JSON.stringify(v) : String(v)
  return `'${s.replace(/'/g, "''")}'`
}
const ident = (n) => (/^[a-z_][a-z0-9_]*$/.test(n) ? n : `"${n}"`)

console.log(`projeto ${ref}\n`)

const tabelas = (await sql(
  `select c.relname, c.relrowsecurity from pg_class c join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind = 'r' order by 1`,
)).map((t) => ({ nome: t.relname, rls: t.relrowsecurity }))

const colunas = await sql(
  `select c.relname as tbl, a.attname as col, format_type(a.atttypid, a.atttypmod) as typ,
          a.attnotnull as notnull, pg_get_expr(d.adbin, d.adrelid) as def, a.attidentity as ident
   from pg_attribute a
   join pg_class c on c.oid = a.attrelid
   join pg_namespace n on n.oid = c.relnamespace
   left join pg_attrdef d on d.adrelid = c.oid and d.adnum = a.attnum
   where n.nspname = 'public' and c.relkind = 'r' and a.attnum > 0 and not a.attisdropped
   order by c.relname, a.attnum`,
)

const constraints = await sql(
  `select conrelid::regclass::text as tbl, conname, contype, pg_get_constraintdef(oid) as def
   from pg_constraint where connamespace = 'public'::regnamespace
   order by case contype when 'p' then 1 when 'u' then 2 when 'c' then 3 else 4 end, conname`,
)

const indices = await sql(
  `select tablename as tbl, indexname, indexdef from pg_indexes
   where schemaname = 'public'
     and indexname not in (select conname from pg_constraint where connamespace = 'public'::regnamespace)
   order by 1, 2`,
)

const policies = await sql(
  `select tablename as tbl, policyname, permissive, roles::text as roles, cmd, qual, with_check
   from pg_policies where schemaname = 'public' order by 1, 2`,
)

const funcoes = await sql(
  `select pg_get_functiondef(p.oid) as def from pg_proc p
   join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public' and p.prokind = 'f' order by p.proname`,
)

const triggers = await sql(
  `select pg_get_triggerdef(t.oid) as def from pg_trigger t
   join pg_class c on c.oid = t.tgrelid
   join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and not t.tgisinternal order by t.tgname`,
)

// ---- schema.sql -------------------------------------------------------------
const S = [`-- gym-track / ${ref} — schema public em ${new Date().toISOString()}`, '', 'set search_path = public;', '']
for (const { nome } of tabelas) {
  const cols = colunas.filter((c) => c.tbl === nome).map((c) => {
    let l = `  ${ident(c.col)} ${c.typ}`
    if (c.ident === 'a') l += ' generated always as identity'
    else if (c.ident === 'd') l += ' generated by default as identity'
    else if (c.def) l += ` default ${c.def}`
    if (c.notnull) l += ' not null'
    return l
  })
  S.push(`create table if not exists public.${ident(nome)} (\n${cols.join(',\n')}\n);`, '')
}
for (const c of constraints) {
  S.push(`alter table ${c.tbl} add constraint ${ident(c.conname)} ${c.def};`)
}
S.push('')
for (const i of indices) S.push(`${i.indexdef};`)
S.push('')
for (const f of funcoes) S.push(`${f.def};`, '')
for (const t of triggers) S.push(`${t.def};`)
S.push('')
for (const { nome, rls } of tabelas) {
  if (rls) S.push(`alter table public.${ident(nome)} enable row level security;`)
}
S.push('')
for (const p of policies) {
  const roles = p.roles.replace(/[{}]/g, '')
  let l = `create policy ${lit(p.policyname)} on public.${ident(p.tbl)}`
  l += ` as ${p.permissive === 'PERMISSIVE' ? 'permissive' : 'restrictive'} for ${p.cmd.toLowerCase()} to ${roles}`
  if (p.qual) l += `\n  using (${p.qual})`
  if (p.with_check) l += `\n  with check (${p.with_check})`
  S.push(`${l};`)
}

// ---- dados ------------------------------------------------------------------
const stamp = new Date().toISOString().slice(0, 16).replace('T', '_').replace(':', '')
const out = `backups/${stamp}`
mkdirSync(out, { recursive: true })

const D = ['-- dados: rode depois de schema.sql', 'set session_replication_role = replica;', '']
const dados = {}
const resumo = {}

for (const { nome } of tabelas) {
  const rows = await sql(`select * from public.${ident(nome)}`)
  dados[nome] = rows
  resumo[nome] = rows.length
  console.log(`${nome.padEnd(20)} ${String(rows.length).padStart(5)} linhas`)
  if (!rows.length) continue
  const cols = Object.keys(rows[0])
  D.push(`insert into public.${ident(nome)} (${cols.map(ident).join(', ')}) values`)
  D.push(rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(', ')})`).join(',\n') + ';', '')
}
D.push("set session_replication_role = 'origin';")

writeFileSync(`${out}/schema.sql`, S.join('\n') + '\n')
writeFileSync(`${out}/data.sql`, D.join('\n') + '\n')
writeFileSync(`${out}/dados.json`, JSON.stringify(dados, null, 2))
writeFileSync(`${out}/MANIFEST.json`, JSON.stringify({
  projeto: 'gym-track', ref, gerado: new Date().toISOString(),
  tabelas: resumo, policies: policies.length, indices: indices.length,
  funcoes: funcoes.length, triggers: triggers.length,
}, null, 2))

const total = Object.values(resumo).reduce((a, b) => a + b, 0)
console.log(`\n${total} linhas em ${out}`)
if (!total) { console.error('\nATENÇÃO: zero linhas — backup vazio, não serve.'); process.exit(1) }
console.log('Copie para fora da máquina. São dados de saúde: não commite.')

function fatal(m) { console.error(m); process.exit(1) }
